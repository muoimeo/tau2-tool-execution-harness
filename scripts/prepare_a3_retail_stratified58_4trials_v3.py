def write_once(path: Path, content: str) -> None:
    if path.exists():
        if path.read_text(encoding="utf-8") != content:
            raise RuntimeError(f"refusing to overwrite mismatched frozen artifact: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def prepare(root: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    # A clean root may contain only these planning artifacts before the first
    # CLI invocation. Any runtime artifact indicates a prior/partial run.
    allowed = {"manifest.yaml", "taskset.json", "config-preview.json", "ledger"}
    unexpected = [path.name for path in root.iterdir() if path.name not in allowed]
    if unexpected:
        raise RuntimeError(f"refusing non-clean A3 v3 root; unexpected entries: {unexpected}")

    manifest_text = manifest()
    manifest_sha = hashlib.sha256(manifest_text.encode("utf-8")).hexdigest()
    runs = [
        {
            "run_id": f"a3v3-t{task_id}-r{trial}", "task_id": task_id,
            "task_order_index": order, "trial": trial, "trial_seed": seed,
            "status": "pending",
        }
        for trial, seed in enumerate(_seeds())
        for order, task_id in enumerate(TASK_IDS)
    ]
    if len(runs) != 232 or len({(r["task_id"], r["trial"], r["trial_seed"]) for r in runs}) != 232:
        raise AssertionError("A3 v3 scheduled tuple invariant failed")
    taskset = {
        "schema_version": "a3-main-taskset/v3", "name": "retail-stratified-58-v1",
        "domain": "retail", "task_ids": list(TASK_IDS),
        "native_execution_order": list(TASK_IDS), "num_trials": 4,
        "root_seed": ROOT_SEED, "trial_seeds": list(_seeds()), "planned_episode_count": 232,
    }
    ledger = {
        "ledger_version": 1, "experiment_id": "EXP-A3-Main-retail-stratified-58-v3",
        "task_suite_manifest_sha256": manifest_sha, "root_seed": ROOT_SEED,
        "task_order": list(TASK_IDS), "num_trials": 4, "planned_episode_count": 232,
        "runs": runs,
    }
    config = frozen_config(root)
    if config.get("safe_operational_failure_scope") != "per_logical_episode":
        raise AssertionError("A3 v3 scope was not frozen")
    write_once(root / "manifest.yaml", manifest_text)
    write_once(root / "taskset.json", json.dumps(taskset, indent=2, sort_keys=True) + "\n")
    write_once(root / "ledger" / "scheduled-runs.json", json.dumps(ledger, indent=2, sort_keys=True) + "\n")
    write_once(root / "config-preview.json", json.dumps(config, indent=2, sort_keys=True) + "\n")


def verify(root: Path) -> None:
    config = json.loads((root / "config-preview.json").read_text(encoding="utf-8"))
    ledger = json.loads((root / "ledger" / "scheduled-runs.json").read_text(encoding="utf-8"))
    tuples = {(row["task_id"], row["trial"], row["trial_seed"]) for row in ledger["runs"]}
    assert ledger["planned_episode_count"] == len(ledger["runs"]) == len(tuples) == 232
    assert config["safe_operational_failure_scope"] == "per_logical_episode"
    assert config["max_operational_failures"] == 3
    assert config["provider_max_attempts"] == 3
    assert config["provider_internal_num_retries"] == 0
    print("A3-Main v3 dry-run PASS")
    print(f"root={root}")
    print("planned=232 unique_task_trial_seed=232")
    print("scope=per_logical_episode; safe_episode_attempt_budget=3; A1/A2/A3=on")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=("prepare", "verify"))
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.root)
    else:
        verify(args.root)


if __name__ == "__main__":
    main()
