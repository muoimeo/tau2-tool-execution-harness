def _seeds() -> tuple[int, ...]:
    generated = tuple(random.Random(ROOT_SEED).randint(0, 1_000_000) for _ in range(4))
    # Do not use four fresh Random instances: the frozen native mapping is
    # generated by one PRNG sequence.
    rng = random.Random(ROOT_SEED)
    generated = tuple(rng.randint(0, 1_000_000) for _ in range(4))
    if generated != TRIAL_SEEDS:
        raise AssertionError(f"unexpected native trial seeds: {generated}")
    return generated


def frozen_config(root: Path) -> dict:
    return A1RunSettings.create(
        trace_root=root / "traces", domain="retail", task_ids=TASK_IDS,
        agent="llm_agent", user="user_simulator", llm_agent="openai/claude-sonnet-5",
        llm_user="openai/claude-opus-4-8", num_trials=4, trial_seeds=_seeds(),
        max_steps=200, max_errors=10, max_concurrency=1, root_seed=ROOT_SEED,
        llm_args_agent=AGENT_ARGS, llm_args_user=USER_ARGS, a2_retry=True,
        a3_recovery=True, a2_max_operational_failures=3,
        a2_safe_operational_failure_scope="per_logical_episode",
        a2_max_unsafe_manual_resumes=2,
    ).config_payload


